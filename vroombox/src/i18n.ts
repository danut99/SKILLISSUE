export const lang: 'ro' | 'en' =
  typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('ro') ? 'ro' : 'en'

export const t: Strings = lang === 'ro' ? ro : en

export function randomName(): string {
  const pick = <T>(a: T[]) => a[Math.floor(Math.random() * a.length)]
  return lang === 'ro' ? `${pick(t.nameNouns)} ${pick(t.nameAdjs)}` : `${pick(t.nameAdjs)} ${pick(t.nameNouns).replace(/^The /, '')}`
}
